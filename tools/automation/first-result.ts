#!/usr/bin/env node

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import {
  LocalSemantiqEngine,
  SEMANTIQ_MATURITY,
  SEMANTIQ_RELEASE_VERSION,
  type BenchmarkReport,
  type BenchmarkSubject,
  type ScoringProfile
} from "../../packages/semantiq/src/index.js";
import { PRODUCT_CONTRACTS_SCHEMA_VERSION } from "../../packages/sandbox-contracts/src/product-contracts.js";

export const FIRST_RESULT_OUTPUT_PATH = "artifacts/first-result/semantiq-result.json";

const subject: BenchmarkSubject = {
  id: "smoke_subject_001",
  kind: "question",
  version: PRODUCT_CONTRACTS_SCHEMA_VERSION,
  title: "How does explainable scoring ensure reproducibility?",
  content: "Explainable scoring relies on deterministic weights and clear evidence citations.",
  contextIds: [],
  evidenceIds: ["ev_001"]
};

const profile: ScoringProfile = {
  id: "profile_smoke",
  version: PRODUCT_CONTRACTS_SCHEMA_VERSION,
  name: "Smoke Profile",
  weights: { "question-quality": 1.0, "reasoning-quality": 1.0 }
};

export async function evaluateLocalScaffold(): Promise<BenchmarkReport> {
  return new LocalSemantiqEngine().evaluate(subject, profile);
}

function deterministicPayload(report: BenchmarkReport) {
  const { id: _runtimeId, createdAt: _runtimeTimestamp, ...payload } = report;
  void _runtimeId;
  void _runtimeTimestamp;
  return payload;
}

export async function createFirstResultArtifact(outputPath = FIRST_RESULT_OUTPUT_PATH) {
  const repositoryRoot = process.cwd();
  const artifactsRoot = resolve(repositoryRoot, "artifacts");
  const absoluteOutputPath = resolve(repositoryRoot, outputPath);
  const relativeToArtifacts = relative(artifactsRoot, absoluteOutputPath);

  if (
    relativeToArtifacts === "" ||
    relativeToArtifacts.startsWith("..") ||
    isAbsolute(relativeToArtifacts)
  ) {
    throw new Error("First-result output must be a file below the repository artifacts directory.");
  }

  const report = await evaluateLocalScaffold();
  const artifact = {
    schemaVersion: PRODUCT_CONTRACTS_SCHEMA_VERSION,
    software: {
      name: "SemantIQ",
      releaseVersion: SEMANTIQ_RELEASE_VERSION,
      maturity: SEMANTIQ_MATURITY
    },
    runMetadata: {
      mode: "deterministic-local-scaffold",
      fixture: "smoke_subject_001/profile_smoke",
      timestampPolicy: "omitted-for-byte-reproducibility",
      networkAccess: "not-required"
    },
    evidenceClassification: {
      origin: "internal",
      input: "synthetic",
      replicationStatus: "not-independent-replication"
    },
    result: {
      sourceContract: "BenchmarkReport",
      omittedRuntimeFields: ["id", "createdAt"],
      payload: deterministicPayload(report)
    },
    limitations: [
      "This artifact is generated by an owner-controlled local scaffold using synthetic input.",
      "It is not external replication, benchmark validation, scientific validation, certification, adoption, production evidence, or production usage.",
      "Production scoring logic is not implemented in this scaffold."
    ]
  } as const;

  await mkdir(dirname(absoluteOutputPath), { recursive: true });
  await writeFile(absoluteOutputPath, `${JSON.stringify(artifact, null, 2)}\n`, "utf8");

  return {
    artifact,
    outputPath: relative(repositoryRoot, absoluteOutputPath).replaceAll("\\", "/")
  };
}

function outputArgument(argv: readonly string[]): string {
  const index = argv.indexOf("--output");
  if (index === -1) return FIRST_RESULT_OUTPUT_PATH;
  const value = argv[index + 1];
  if (!value) throw new Error("--output requires a repository-local path below artifacts/.");
  return value;
}

async function runCli(): Promise<void> {
  try {
    const { outputPath } = await createFirstResultArtifact(outputArgument(process.argv.slice(2)));
    console.log(`[PASS] Internal synthetic SemantIQ first result written to ${outputPath}`);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(`[FAIL] Unable to generate first result: ${message}`);
    process.exitCode = 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await runCli();
}
